using System.Collections.Generic;

/// <summary>
/// Таблица допустимых раскладок препятствий в одном ряду.
///
/// Ряд — это три полосы, записанные тремя символами:
///   '.' — пусто
///   'B' — высокое препятствие (только объехать)
///   'J' — низкое (перепрыгнуть)
///   'S' — балка сверху (подкат)
///   'T' — поезд. В таблицах НЕ встречается: его подставляет генератор,
///         занимая полосу на весь чанк.
///
/// Для всех проверок ниже 'T' ведёт себя как 'B' — то есть считается
/// непроходимым. Это сознательно строже, чем на самом деле: по крыше поезда
/// пробежать можно. Но гарантия обязана держаться на наземном пути, иначе
/// «трасса проходима» превратится в «проходима, если успеешь запрыгнуть».
/// Поезд остаётся выбором, а не обязанностью.
///
/// Правило безопасности из ТЗ выполняется по построению: в таблице нет
/// ни одной раскладки без прохода. Если в ряду нет ни одной точки '.',
/// то все три полосы обязаны быть одного проходимого типа (JJJ или SSS).
/// Комбинаций вида "BJS" здесь нет и быть не может.
/// </summary>
public static class ObstaclePatterns
{
    private static readonly string[] Tier0 =
    {
        "...", "...",
        "B..", ".B.", "..B",
        "J..", ".J.", "..J"
    };

    private static readonly string[] Tier1 =
    {
        "...",
        "B..", ".B.", "..B",
        "J..", ".J.", "..J",
        "S..", ".S.", "..S",
        "BB.", ".BB", "B.B",
        "JJJ"
    };

    private static readonly string[] Tier2 =
    {
        "...",
        "B..", ".B.", "..B",
        "J..", ".J.", "..J",
        "S..", ".S.", "..S",
        "BB.", ".BB", "B.B",
        "JJ.", ".JJ", "J.J",
        "SS.", ".SS", "S.S",
        "BJ.", ".JB", "JB.", ".BJ",
        "BS.", ".SB", "SB.", ".BS",
        "JJJ", "SSS"
    };

    private static readonly string[] Tier3 =
    {
        "B..", ".B.", "..B",
        "J..", ".J.", "..J",
        "S..", ".S.", "..S",
        "BB.", ".BB", "B.B",
        "JJ.", ".JJ", "J.J",
        "SS.", ".SS", "S.S",
        "BJ.", ".JB", "JB.", ".BJ",
        "BS.", ".SB", "SB.", ".BS",
        "JS.", ".SJ", "SJ.", ".JS",
        "JJJ", "SSS"
    };

    /// <summary>
    /// Кривая сложности. Изначально было 200 / 600 / 1200 метров, но при
    /// стартовой скорости 14 это означало, что первую минуту игрок видит
    /// одиночные препятствия по одному ряду на чанк. Сжато вчетверо:
    /// разминка длится 60 метров, дальше сложность растёт заметно.
    /// </summary>
    public static int TierForDistance(float distance)
    {
        if (distance < 60f) return 0;
        if (distance < 300f) return 1;
        if (distance < 800f) return 2;
        return 3;
    }

    public static IReadOnlyList<string> ForTier(int tier)
    {
        switch (tier)
        {
            case 0: return Tier0;
            case 1: return Tier1;
            case 2: return Tier2;
            default: return Tier3;
        }
    }

    /// <summary>Сколько рядов чанка заполняем на этой сложности.</summary>
    public static int RowsForTier(int tier) => tier == 0 ? 1 : 2;

    /// <summary>
    /// Ряд, в котором нет ни одной пустой полосы, требует действия
    /// (прыжка или подката) — такие ряды нельзя ставить слишком часто.
    /// </summary>
    public static bool RequiresAction(string pattern) => !pattern.Contains(".");

    /// <summary>
    /// Полосы, по которым можно проехать этот ряд.
    /// Для JJJ и SSS проходимы все три — просто надо вовремя нажать.
    /// </summary>
    public static bool[] PassableLanes(string pattern)
    {
        var lanes = new bool[3];

        // Есть куда встать без действий — считаем проходимыми только пустые
        // полосы. Так генератор предпочитает честный объезд прыжку.
        if (pattern.Contains("."))
        {
            for (int i = 0; i < 3; i++) lanes[i] = pattern[i] == '.';
            return lanes;
        }

        // Пустых полос нет: ряд можно пройти только действием, и только если
        // все полосы (кроме поезда) требуют ОДНОГО И ТОГО ЖЕ действия —
        // одним жестом двух разных не сделать.
        //
        // Раньше здесь стояло безусловное «все три проходимы»: в таблице
        // рядов без пустот всего два, JJJ и SSS, и оба однородны. Но генератор
        // подставляет поезда уже поверх таблицы, и ряд вида BJT пустот не имеет,
        // при этом однородным не является. Без этой проверки блок в такой
        // раскладке считался бы проходимым.
        char action = '\0';
        bool uniform = true;

        for (int i = 0; i < 3; i++)
        {
            if (pattern[i] == 'T') continue;          // поезд обходим поверху, не в счёт

            if (pattern[i] != 'J' && pattern[i] != 'S')
            {
                uniform = false;
                break;
            }

            if (action == '\0') action = pattern[i];
            else if (pattern[i] != action) { uniform = false; break; }
        }

        for (int i = 0; i < 3; i++) lanes[i] = uniform && pattern[i] != 'T';

        return lanes;
    }

    /// <summary>
    /// Есть ли вообще хоть одна проходимая полоса.
    ///
    /// В самой таблице непроходимых раскладок нет по построению, но генератор
    /// подставляет в раскладку символ 'T' — поезд, — и он способен занять
    /// последнюю свободную полосу. Поэтому итоговую раскладку проверяем
    /// отдельно, а не полагаемся на таблицу.
    /// </summary>
    public static bool HasPassableLane(bool[] lanes)
    {
        for (int i = 0; i < lanes.Length; i++)
        {
            if (lanes[i]) return true;
        }
        return false;
    }

    /// <summary>
    /// Есть ли полоса, проходимая и в предыдущем ряду, и в этом.
    /// Если есть — игрок гарантированно проедет, даже не перестраиваясь.
    /// </summary>
    public static bool SharesLane(bool[] previous, bool[] next)
    {
        for (int i = 0; i < 3; i++)
        {
            if (previous[i] && next[i]) return true;
        }
        return false;
    }
}
