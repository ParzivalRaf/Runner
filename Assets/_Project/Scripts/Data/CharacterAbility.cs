/// <summary>
/// Пассивные способности персонажей. Все работают сами, без кнопок —
/// игрок выбрал учителя в меню и дальше просто бежит.
///
/// Смысл числа abilityValue у CharacterData зависит от способности,
/// поэтому он описан прямо здесь, рядом с вариантами.
/// </summary>
public enum CharacterAbility
{
    /// <summary>Ничего особенного. Стартовый персонаж. Значение не используется.</summary>
    None = 0,

    /// <summary>Больше монет. Значение — доля: 0.10 это +10%.</summary>
    CoinBonus = 1,

    /// <summary>Бонусы держатся дольше. Значение — секунды: 2 это +2 с к каждому.</summary>
    LongerPowerUps = 2,

    /// <summary>Щит: прощает столкновения. Значение — сколько раз за забег.</summary>
    Shield = 3,

    /// <summary>Забег начинается на большей скорости. Значение — юниты в секунду.</summary>
    FastStart = 4
}
